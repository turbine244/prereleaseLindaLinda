#pragma once

/*
  Standard type of return-code(TYPE_rc) & utilities.

    format : int8_t
    use    : [0]        = success
             [-1, -127] = errors generated by the current function
             [1, 127]   = errors returned by called functions, normalized with to_abs(...)
             [-128]     = unused; it cannot be normalized to a positive TYPE_rc value             
*/

#include <iostream>
#include <cstdint>
#include <string>
#include <iomanip>

//====----====----====----====----====----====----====----====---- TYPE

using TYPE_rc = int8_t;

//====----====----====----====----====----====----====----====---- FDEC

static inline TYPE_rc to_abs(TYPE_rc rc);
static inline void vd_printErrorRc(TYPE_rc rc, const std::string& message);
static inline void vd_printErrorVendor(const std::string& nameVendor, const std::string& message);

//====----====----====----====----====----====----====----====---- FDEF

static inline TYPE_rc to_abs(TYPE_rc rc)
{
  if (rc < 0)
  {
    return -rc; 
  }
  return rc;
}

static inline void vd_printErrorRc(TYPE_rc rc, const std::string& message)
{  
  std::cerr 
    << "ERROR "
    << "(0x" 
    << std::hex << std::uppercase << std::setw(2) << std::setfill('0') 
    << static_cast<unsigned int>(static_cast<uint8_t>(rc))
    << ") : "
    << message << std::dec << std::endl;  
}

static inline void vd_printErrorVendor(const std::string& nameVendor, const std::string& message)
{
  std::cerr
    << "ERROR [" << nameVendor << "] : "
    << message << std::endl;
}
